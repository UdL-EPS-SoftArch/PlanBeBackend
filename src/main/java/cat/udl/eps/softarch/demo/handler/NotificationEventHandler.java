package cat.udl.eps.softarch.demo.handler;

import cat.udl.eps.softarch.demo.domain.Notification;
import org.springframework.data.rest.core.annotation.HandleBeforeCreate;
import org.springframework.data.rest.core.annotation.HandleBeforeDelete;
import org.springframework.data.rest.core.annotation.HandleBeforeLinkDelete;
import org.springframework.data.rest.core.annotation.HandleBeforeLinkSave;
import org.springframework.data.rest.core.annotation.HandleBeforeSave;
import org.springframework.data.rest.core.annotation.RepositoryEventHandler;
import org.springframework.http.HttpStatus;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.stereotype.Component;
import org.springframework.web.server.ResponseStatusException;

import java.util.Objects;

/**
 * Defence in depth: WebSecurityConfig already denies POST/PUT/DELETE on /notifications.
 * Through the API a user can only flip the {@code read} flag of a notification addressed to them.
 */
@Component
@RepositoryEventHandler
public class NotificationEventHandler {

    @HandleBeforeCreate
    public void handleNotificationPreCreate(Notification notification) {
        throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Notifications are generated by the system");
    }

    @HandleBeforeDelete
    public void handleNotificationPreDelete(Notification notification) {
        throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Notifications cannot be deleted");
    }

    @HandleBeforeLinkSave
    public void handleNotificationPreLinkSave(Notification notification, Object linked) {
        throw new ResponseStatusException(HttpStatus.FORBIDDEN, "The recipient of a notification cannot be changed");
    }

    @HandleBeforeLinkDelete
    public void handleNotificationPreLinkDelete(Notification notification, Object linked) {
        throw new ResponseStatusException(HttpStatus.FORBIDDEN, "The recipient of a notification cannot be changed");
    }

    @HandleBeforeSave
    public void handleNotificationPreSave(Notification notification) {
        Notification.LoadedState before = notification.loadedState();
        if (before == null) {
            // Only reachable if the entity was not loaded from the DB: refuse instead of guessing.
            throw new IllegalStateException("Notification " + notification.getId() + " has no loaded state");
        }
        String username = SecurityContextHolder.getContext().getAuthentication().getName();
        // #41 "marca como leidas las suyas": only the recipient, not even an ADMIN (who can only read them).
        if (!username.equals(before.recipientId())) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Only the recipient can modify a notification");
        }
        String recipientId = notification.getRecipient() == null ? null : notification.getRecipient().getId();
        boolean onlyReadChanged = Objects.equals(before.recipientId(), recipientId)
            && before.type() == notification.getType()
            && Objects.equals(before.message(), notification.getMessage())
            && Objects.equals(before.targetUri(), notification.getTargetUri())
            && Objects.equals(before.created(), notification.getCreated());
        if (!onlyReadChanged) {
            throw new ResponseStatusException(HttpStatus.FORBIDDEN, "Only the read flag of a notification can be modified");
        }
    }
}
